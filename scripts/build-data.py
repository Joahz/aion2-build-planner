"""Compact data-src/*.json (scraped from gamers4.life) into data/game-data.js.

The app loads game-data.js with a <script> tag, so it works from file:// in
Electron and in tests without a server. Run: python3 scripts/build-data.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'data-src'
OUT = ROOT / 'data' / 'game-data.js'


def load(name):
    return json.loads((SRC / name).read_text(encoding='utf-8'))


def skill(s):
    return {
        'id': s['id'], 'name': s['name'], 'type': s['type'],
        'damageType': s.get('damageType'), 'desc': s['description'],
        'cd': s.get('cooldownMs') or 0, 'mp': s.get('mpCost') or 0,
        'range': (s.get('rangeCm') or {}).get('max'),
        'icon': s.get('icon'),
        'specs': [{'lvl': x['level'], 'text': x['text']} for x in s.get('specs') or []],
        'refs': s.get('referencedSkills') or [],
        'boosts': [{'board': b['board'], 'node': b['nodeId'], 'plus': b['plusLevels']}
                   for b in s.get('daevanionBoostNodes') or []],
    }


def item(i):
    d = i.get('detail') or {}
    name = i['name']
    # The source names some necklaces "... Earrings"; the slot is right, the name isn't.
    if i['slot'] == 'necklace' and name.endswith(' Earrings'):
        name = name[: -len(' Earrings')] + ' Necklace'
    out = {
        'id': i['id'], 'name': name, 'race': i.get('race') or 'all', 'slot': i['slot'], 'grade': i.get('gradeName'),
        'level': i.get('level'), 'ilvl': i.get('itemLevel'), 'family': i.get('family'),
        'maxEnch': i.get('maxEnchantBonus') or {},
    }
    if d:
        out['base'] = d.get('mainStats') or {}
        out['ench'] = [e['stats'] for e in d.get('enchants') or []]
        drops = d.get('droppedBy') or []
        if drops:
            names = [x.get('name') for x in drops if x.get('name')]
            out['drops'] = list(dict.fromkeys(names))[:4]
    return out


def main():
    classes = {c['key']: c for c in load('classes.json')['classes']}
    stats = load('stats.json')
    builds = load('builds.json')['builds']
    data = {'classes': {}, 'stats': {}, 'items': [], 'builds': []}
    for key, c in classes.items():
        sk = load(f'skills-{key}.json')
        data['classes'][key] = {
            'key': key, 'name': c['name'], 'role': c['role'], 'weapon': c['weaponSlots'][0],
            'summary': c['summary'], 'guide': c['guide'],
            'skills': [skill(s) for s in sk['skills']],
        }
    for s in stats['definitions']:
        data['stats'][s['id']] = {'label': s['label'] or s['id'], 'pct': s['isPercent'], 'group': s['group']}
    data['items'] = [item(i) for i in load('items-scout.json')['items']]
    for b in builds:
        if not b['skills']:
            continue
        data['builds'].append({
            'id': b['id'], 'title': b['title'], 'class': b['class'], 'author': b['author'],
            'views': b['views'], 'updated': b['updatedAt'], 'url': b['plannerUrl'],
            'skills': [s['id'] for s in b['skills']],
            'gear': {slot: {'id': g['id'], 'name': g['name']} for slot, g in (b['equipment'] or {}).items()},
        })
    js = '// Generated by scripts/build-data.py from data-src/ (source: gamers4.life). Do not edit.\n'
    js += 'window.GAME = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n'
    OUT.write_text(js, encoding='utf-8')
    print(f'{OUT.name}: {len(js) / 1e6:.2f} MB, {len(data["items"])} items, '
          f'{sum(len(c["skills"]) for c in data["classes"].values())} skills, {len(data["builds"])} builds')


main()
